def _eur(value) -> str:
    return f"{'-' if value < 0 else ''}€{abs(value):,.2f}"


def render_html(batch: Batch) -> str:
    clean = sum(1 for i in batch.invoices if batch.status(i) == "ok")
    tiles = [("Files read", f"{len(batch.invoices)} of {len(batch.invoices) + len(batch.unreadable)}"),
             ("Ready to book", f"{clean}"), ("Total due, without duplicates", _eur(batch.total_due)),
             ("Errors · warnings", f"{sum(1 for i in batch.issues if i.severity == 'error')} · "
                                   f"{sum(1 for i in batch.issues if i.severity == 'warning')}")]
    tiles_html = "".join(f'<div class="tile"><div class="label">{l}</div><div class="value">{v}</div></div>' for l, v in tiles)

    inv_rows = "".join(
        "<tr>"
        f'<td><span class="badge {batch.status(i)}">{batch.status(i)}</span></td>'
        f"<td>{escape(i.seller_name)}</td><td>{escape(i.number)}</td>"
        f'<td>{i.issue_date or ""}</td><td class="muted">{i.syntax}{" · credit note" if i.doc_type == "credit_note" else ""}</td>'
        f'<td class="num">{_eur(i.sign * (i.payable or 0))}</td>'
        "</tr>" for i in batch.invoices)
    sup_rows = "".join(
        f"<tr><td>{escape(s.name)}</td><td class=\"muted\">{escape(s.vat)}</td><td class=\"num\">{s.invoices}</td>"
        f'<td class="num">{_eur(s.net)}</td><td class="num">{_eur(s.tax)}</td><td class="num">{_eur(s.gross)}</td></tr>'
        for s in batch.suppliers)
    issue_rows = "".join(
        f'<tr><td><span class="badge {i.severity}">{i.severity}</span></td><td>{escape(i.source_file)}</td>'
        f'<td>{i.code}</td><td class="muted">{escape(i.rule)}</td><td class="details">{escape(i.message)}</td></tr>'
        for i in batch.issues) or '<tr><td colspan="5">No issues found.</td></tr>'

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>E-invoice batch</title><style>{CSS}</style></head>
<body><div class="wrap">
<h1>E-invoice batch</h1>
<p class="sub">UBL (Peppol BIS 3.0) and CII (Factur-X / ZUGFeRD / XRechnung) invoices checked against EN 16931 rules.</p>
<div class="tiles">{tiles_html}</div>
<h2>Invoices</h2>
<div class="card"><table><thead><tr><th>Status</th><th>Seller</th><th>Number</th><th>Date</th><th>Format</th><th>Total due</th></tr></thead>
<tbody>{inv_rows}</tbody></table></div>
<h2>Issues ({len(batch.issues)})</h2>
<div class="card"><table><thead><tr><th>Severity</th><th>File</th><th>Issue</th><th>Rule</th><th>Details</th></tr></thead>
<tbody>{issue_rows}</tbody></table></div>
<h2>By supplier</h2>
<div class="card"><table><thead><tr><th>Supplier</th><th>VAT number</th><th>Docs</th><th>Net</th><th>VAT</th><th>Total</th></tr></thead>
<tbody>{sup_rows}</tbody></table></div>
<footer>Generated by einvoice-reader. Credit notes are shown as negative amounts.</footer>
</div></body></html>
"""


def write_html(batch: Batch, path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_html(batch), encoding="utf-8")
    return path
